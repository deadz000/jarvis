/**
 * Worker 提示词（提示词设计的基础设施）。
 *
 * ## 核心设计：结果有两个受众
 * Worker 的产出会被**两个地方**消费，需求不同：
 * 1. **面板 / 历史记录**：要完整、可含 Markdown、列表、代码块；
 * 2. **语音播报（TTS）**：要口语化、短、无 Markdown、无代码、无 URL、无路径。
 *
 * 因此契约是「完整结果 + 一段口语稿」，而不是一份文本硬凑两种用途。
 * 口语稿是**概率性输出**，所以解析侧有确定性兜底（见 `spoken-text.ts`）：
 * 模型忘记给、给成 markdown、给超长，都不会导致播报失败或念出代码。
 *
 * ## 为什么还要"事实标记"
 * 重要性是**相对的**（需要参照物），Worker 只看得见自己的目标，给不出重要性；
 * 但它能可靠地报出**结果自身的事实**（阻塞 / 需要决策 / 坏消息），
 * 这些事实再交给能看到全局的层去判断该不该打断用户。
 */
import { SPOKEN_BLOCK_END, SPOKEN_BLOCK_START } from "../delivery/spoken-text.ts";

export function buildWorkerPrompt(goal: string): string {
  return [
    `你的目标：${goal}`,
    "",
    "请完成这个目标，然后**严格按下面的结构**输出（系统会解析它）：",
    "",
    "### 第一部分：完整结果",
    "面板与历史记录会展示这一段。可以用 Markdown、列表、表格、代码块，",
    "把关键信息、数据与依据都写清楚。",
    "",
    `### 第二部分：口语播报稿（放在 ${SPOKEN_BLOCK_START} 与 ${SPOKEN_BLOCK_END} 之间）`,
    "这一段会被语音合成为**播报**，因此：",
    "- 1～3 句，像对人说话一样直接说结论；",
    "- 不要出现 Markdown、代码、列表、链接、表格、文件路径；",
    "- 不要把命令输出的原文念出来，只说它意味着什么；",
    "- 如果这次结果没有值得播报的内容，这一段就留空。",
    "",
    "### 额外要求",
    "- 不要编造：无法确认的信息要明确说明不确定；",
    "- 如果**目标未完成或被阻塞**、**需要用户做决定才能继续**、",
    "  或**发现了额外的风险/坏消息**，请在完整结果里用一句平实的话明确写出来，不要夸大也不要隐瞒；",
    "- 不要输出与目标无关的客套话。",
  ].join("\n");
}
